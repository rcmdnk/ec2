cleanup_resources() {
  # Show or execute cleanup for resources recorded by environment commands.
  _environment_args
  _environment_cleanup_args
  _environment_runtime cleanup_resources "${__environment_cleanup_args[@]}"
}

init_environment() {
  # Install an example environment configuration without overwriting one.
  if [ -e "$__environment_config" ] || [ -L "$__environment_config" ];then
    echo "Environment configuration already exists: $__environment_config" >&2
    return 1
  fi
  (
    set -e
    local runtime temporary
    runtime=$(mktemp -d "${TMPDIR:-/tmp}/ec2-environment.XXXXXX")
    trap 'command rm -rf "$runtime"' EXIT
    _environment_extract "$runtime"
    mkdir -p "$(dirname "$__environment_config")"
    temporary="${__environment_config}.tmp.$$"
    cp "$runtime/config.example" "$temporary"
    chmod 600 "$temporary"
    mv "$temporary" "$__environment_config"
  )
  echo "Installed environment configuration: $__environment_config"
}
